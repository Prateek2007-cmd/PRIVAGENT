#!/usr/bin/env python3
"""Stream B live verification driver (isolated backend, real FreePi provider).

Phases (all via the public HTTP API, frontend never started):
  A. NL research, exact prompt from the brief -> PDF + XLSX, read-back verified.
  B. NL daily 9 AM summary job -> concretised instruction, run-now outcome + notification.
  C. Real 1-minute scheduled research (NL, backend-only, natural execution) ->
     persisted outcome + artifact + notification retrieved after "reconnect".
  D. One-off + pause/resume/cancel cycle on job rows.
Logs to b-transcript.txt (timestamps IST) and b-evidence.json.
"""
import json
import os
import sqlite3
import sys
import time
import urllib.error
import urllib.request
from datetime import datetime, timezone

BASE = "http://127.0.0.1:8000"
# Token is generated by start-backend.sh into data/.local_token (0600);
# never hardcode it — tool-argument redaction mangles literal tokens.
TOKEN = open(os.path.join(
    "/home/hatch/workspace/navigator-audit/worktrees3/stream-B/live",
    "data", ".local_token")).read().strip()
BDIR = "/home/hatch/workspace/navigator-audit/worktrees3/stream-B/live"
DB = os.path.join(BDIR, "data", "privagent.db")
LOGF = open(os.path.join(BDIR, "b-transcript.txt"), "a", encoding="utf-8")
EVIDENCE = {"phases": {}}


def ts():
    return datetime.now(timezone.utc).astimezone().strftime("%Y-%m-%d %H:%M:%S %Z")


def log(msg):
    line = f"[{ts()}] {msg}"
    print(line, flush=True)
    LOGF.write(line + "\n")
    LOGF.flush()


def req(method, path, body=None, raw=False):
    data = json.dumps(body).encode() if body is not None else None
    r = urllib.request.Request(BASE + path, data=data, method=method,
                               headers={"Authorization": f"Bearer {TOKEN}",
                                        "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(r, timeout=120) as resp:
            payload = resp.read()
            return resp.status, (payload if raw else json.loads(payload or b"{}"))
    except urllib.error.HTTPError as e:
        return e.code, (e.read() if raw else {"error": e.read().decode()[:500]})


def db_query(sql, args=()):
    conn = sqlite3.connect(DB)
    conn.row_factory = sqlite3.Row
    try:
        return [dict(r) for r in conn.execute(sql, args).fetchall()]
    finally:
        conn.close()


def new_chat():
    s, b = req("POST", "/api/chat", {})
    assert s == 200, b
    return b["chatId"]


def send(chat_id, instruction):
    s, b = req("POST", f"/api/chat/{chat_id}/message", {"instruction": instruction})
    assert s == 200, b
    return b["taskId"]


def poll_task(task_id, timeout=600, interval=5):
    t0 = time.time()
    last = None
    while time.time() - t0 < timeout:
        s, b = req("GET", f"/api/task/{task_id}")
        if s == 200:
            last = b
            if b.get("taskState") in ("completed", "failed", "cancelled", "awaiting_input"):
                return b, time.time() - t0
        time.sleep(interval)
    return last, time.time() - t0


def get_job(job_id):
    s, b = req("GET", "/api/scheduled")
    assert s == 200, b
    for j in b.get("jobs") or []:
        if j["id"] == job_id:
            return j
    return None


def wait_job_outcome(job_id, timeout=600, interval=5):
    t0 = time.time()
    last = None
    while time.time() - t0 < timeout:
        last = get_job(job_id)
        if last and last.get("last_outcome"):
            return last, time.time() - t0
        time.sleep(interval)
    return last, time.time() - t0


def download(artifact_id, dest):
    s, payload = req("GET", f"/api/artifacts/{artifact_id}/download", raw=True)
    assert s == 200, (s, payload[:200])
    with open(dest, "wb") as f:
        f.write(payload)
    return len(payload)


def readback_pdf(path):
    from pypdf import PdfReader
    r = PdfReader(path)
    text = "\n".join((p.extract_text() or "") for p in r.pages)
    return len(r.pages), text


def readback_xlsx(path):
    import openpyxl
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    try:
        sheets = {}
        for ws in wb.worksheets:
            rows = [[c for c in row if c is not None and str(c).strip()]
                    for row in ws.iter_rows(values_only=True)]
            rows = [r for r in rows if r]
            sheets[ws.title] = rows
        return sheets
    finally:
        wb.close()


# ---------------------------------------------------------------- A: NL research
RESEARCH_PROMPT = (
    "Research on-device AI agents using five credible academic or official sources. "
    "Compare their architecture, performance, privacy and limitations. "
    "Generate a professional PDF report and Excel comparison sheet with citations."
)
log("== PHASE A: NL research (exact brief prompt) ==")
log(f"PROMPT: {RESEARCH_PROMPT}")
t0 = time.time()
chat = new_chat()
log(f"chat: {chat}")
task_a = send(chat, RESEARCH_PROMPT)
log(f"task A: {task_a}")
final_a, dur_a = poll_task(task_a, timeout=600)
log(f"task A settled in {dur_a:.1f}s: state={final_a.get('taskState')} "
    f"stepsDone={final_a.get('stepsDone')} intent={final_a.get('intent')} "
    f"route={json.dumps(final_a.get('route') or {})}")
log(f"task A message (first 800): {str(final_a.get('message') or '')[:800]}")
s, arts_a = req("GET", f"/api/tasks/{task_a}/artifacts")
log(f"artifacts for task A: HTTP {s} -> {json.dumps(arts_a)[:800]}")
ev_a = {"prompt": RESEARCH_PROMPT, "chat_id": chat, "task_id": task_a,
        "duration_s": round(dur_a, 1), "state": final_a.get("taskState"),
        "steps_done": final_a.get("stepsDone"), "intent": final_a.get("intent"),
        "route": final_a.get("route"), "message": final_a.get("message"),
        "artifacts": arts_a}
for art in (arts_a or []):
    dest = os.path.join(BDIR, "verify", art["filename"])
    os.makedirs(os.path.join(BDIR, "verify"), exist_ok=True)
    n = download(art["artifact_id"], dest)
    log(f"downloaded {art['filename']}: {n} bytes -> {dest}")
    if art["file_format"] == "pdf":
        pages, text = readback_pdf(dest)
        domains = [d for d in ("arxiv.org", "wikipedia.org", "developer.android.com",
                               "developer.apple.com", "pytorch.org", "tensorflow.org",
                               "onnx.ai", "nature.com", "ieee.org", "acm.org",
                               "qualcomm.com", "huggingface.co") if d in text]
        cites = text.count("[1]") + text.count("[2]")
        ev_a["pdf"] = {"pages": pages, "chars": len(text), "domains_found": domains,
                       "file_bytes": n}
        log(f"PDF read-back: {pages} page(s), {len(text)} chars, source domains in text: {domains}")
    if art["file_format"] == "xlsx":
        sheets = readback_xlsx(dest)
        blob = json.dumps(sheets)
        domains = [d for d in ("arxiv.org", "wikipedia.org", "developer.android.com",
                               "developer.apple.com", "pytorch.org", "tensorflow.org",
                               "onnx.ai", "nature.com", "ieee.org", "acm.org",
                               "qualcomm.com", "huggingface.co") if d in blob]
        ev_a["xlsx"] = {"sheets": list(sheets.keys()),
                        "rows_per_sheet": {k: len(v) for k, v in sheets.items()},
                        "domains_found": domains, "file_bytes": n}
        log(f"XLSX read-back: sheets={list(sheets.keys())} rows={ {k: len(v) for k, v in sheets.items()} } domains={domains}")
# pipeline metadata from the research package row (tolerate a missing/empty row)
pkgs = db_query("SELECT package_id, topic_title, status, data_json FROM research_packages WHERE task_id=?", (task_a,))
if pkgs and (pkgs[0].get("data_json") or "").strip():
    try:
        data = json.loads(pkgs[0]["data_json"])
    except Exception as exc:
        log(f"package row present but unparsable: {exc}")
        data = None
    if data:
        meta = data.get("metadata", {}).get("pipeline", {})
        ev_a["pipeline"] = meta
        ev_a["sources"] = [{"url": s.get("url"), "domain": s.get("domain"), "title": s.get("title")}
                           for s in (data.get("sources") or {}).values()]
        ev_a["claims_count"] = len(data.get("claims") or {})
        ev_a["evidence_count"] = len(data.get("evidence") or {})
        log(f"pipeline metadata: {json.dumps(meta)[:1200]}")
        log(f"package sources ({len(ev_a['sources'])}): {[s['url'] for s in ev_a['sources']]}")
        log(f"claims={ev_a['claims_count']} evidence={ev_a['evidence_count']}")
else:
    log("no research package row for task A (pipeline failed before saving)")
EVIDENCE["phases"]["A_nl_research"] = ev_a
log("== PHASE A done ==")

# ---------------------------------------------------------------- B: daily summary job
log("== PHASE B: NL daily 9 AM summary job ==")
chat_b = new_chat()
task_b = send(chat_b, "Give me a daily summary of my watches and jobs at 9am")
final_b, dur_b = poll_task(task_b, timeout=120)
log(f"task B settled in {dur_b:.1f}s: state={final_b.get('taskState')} message={str(final_b.get('message') or '')[:400]}")
s, jobs_b = req("GET", "/api/scheduled")
job_b = None
for j in (jobs_b.get("jobs") or []):
    if "summary" in (j.get("objective") or "").lower():
        job_b = j
        break
assert job_b, jobs_b
log(f"job B: id={job_b['id']} schedule={job_b['schedule']} kind={job_b['schedule_kind']} "
    f"next_run_ist={job_b.get('next_run_ist')} status={job_b['status']}")
log(f"job B objective: {job_b.get('objective')}")
log(f"job B instruction: {job_b.get('instruction')}")
ev_b = {"task_id": task_b, "duration_s": round(dur_b, 1), "state": final_b.get("taskState"),
        "message": final_b.get("message"), "job": job_b}
# run-now on the daily job: outcome + notification must now be recorded (DEMO2 fix)
s, rn = req("POST", f"/api/scheduled/{job_b['id']}/run-now")
assert s == 200, rn
task_b2 = rn["taskId"]
log(f"run-now task: {task_b2}")
final_b2, dur_b2 = poll_task(task_b2, timeout=180)
log(f"run-now settled in {dur_b2:.1f}s: state={final_b2.get('taskState')} "
    f"message={str(final_b2.get('message') or '')[:500]}")
time.sleep(3)  # finalizer + broadcast settle
job_b2 = get_job(job_b["id"])
log(f"job B after run-now: last_outcome={job_b2.get('last_outcome')} "
    f"last_run_ist={job_b2.get('last_run_ist')} last_task_id={job_b2.get('last_task_id')} "
    f"summary={job_b2.get('last_run_summary')}")
s, evs_b = req("GET", "/api/monitoring/events?unread=true&limit=100")
notes_b = [e for e in (evs_b.get("events") or []) if e.get("mission_id") == job_b["id"]]
log(f"unread events for job B: {json.dumps(notes_b)[:800]}")
ev_b["run_now"] = {"task_id": task_b2, "duration_s": round(dur_b2, 1),
                   "state": final_b2.get("taskState"), "message": final_b2.get("message"),
                   "job_after": job_b2, "notifications": notes_b}
EVIDENCE["phases"]["B_daily_summary"] = ev_b
log("== PHASE B done ==")

# ---------------------------------------------------------------- C: 1-minute scheduled research
log("== PHASE C: real 1-minute scheduled research (NL, backend-only, natural run) ==")
chat_c = new_chat()
sched_prompt = (
    "In 1 minute, research on-device AI agents using five credible academic or official sources. "
    "Compare their architecture, performance, privacy and limitations. "
    "Generate a professional PDF report and Excel comparison sheet with citations."
)
task_c = send(chat_c, sched_prompt)
final_c, dur_c = poll_task(task_c, timeout=120)
log(f"schedule-creation task settled in {dur_c:.1f}s: state={final_c.get('taskState')} "
    f"message={str(final_c.get('message') or '')[:500]}")
s, jobs_c = req("GET", "/api/scheduled")
job_c = None
for j in (jobs_c.get("jobs") or []):
    if j["id"] != job_b["id"] and (j.get("schedule_kind") == "once"):
        job_c = j
assert job_c, jobs_c
log(f"job C: id={job_c['id']} schedule={job_c['schedule']} kind={job_c['schedule_kind']} "
    f"next_run_ist={job_c.get('next_run_ist')} status={job_c['status']}")
log(f"job C objective: {job_c.get('objective')}")
log("frontend state: NO frontend process running (backend-only by construction); "
    "waiting for the natural scheduled run...")
job_c2, dur_c2 = wait_job_outcome(job_c["id"], timeout=600)
log(f"job C outcome arrived after {dur_c2:.1f}s: last_outcome={job_c2.get('last_outcome')} "
    f"last_run_ist={job_c2.get('last_run_ist')} last_task_id={job_c2.get('last_task_id')} "
    f"summary={job_c2.get('last_run_summary')} artifacts={json.dumps(job_c2.get('last_artifacts'))[:600]}")
ev_c = {"schedule_task_id": task_c, "schedule_message": final_c.get("message"),
        "job": job_c2, "wait_s": round(dur_c2, 1)}
if job_c2.get("last_task_id"):
    s, b = req("GET", f"/api/task/{job_c2['last_task_id']}")
    ev_c["run_task"] = {"state": b.get("taskState"), "stepsDone": b.get("stepsDone"),
                        "intent": b.get("intent"), "route": b.get("route"),
                        "message": str(b.get("message") or "")[:600]}
    log(f"scheduled run task: {json.dumps(ev_c['run_task'])[:800]}")
    s, arts_c = req("GET", f"/api/tasks/{job_c2['last_task_id']}/artifacts")
    ev_c["artifacts"] = arts_c
    log(f"scheduled-run artifacts: {json.dumps(arts_c)[:600]}")
    for art in (arts_c or []):
        dest = os.path.join(BDIR, "verify", "scheduled-" + art["filename"])
        n = download(art["artifact_id"], dest)
        log(f"downloaded scheduled {art['filename']}: {n} bytes")
        if art["file_format"] == "pdf":
            pages, text = readback_pdf(dest)
            ev_c["pdf"] = {"pages": pages, "chars": len(text)}
            log(f"scheduled PDF read-back: {pages} page(s), {len(text)} chars")
        if art["file_format"] == "xlsx":
            sheets = readback_xlsx(dest)
            ev_c["xlsx"] = {"sheets": list(sheets.keys()),
                            "rows_per_sheet": {k: len(v) for k, v in sheets.items()}}
            log(f"scheduled XLSX read-back: {ev_c['xlsx']}")
# notification retrieval AFTER reconnect (missed-event pull)
s, evs_c = req("GET", "/api/monitoring/events?unread=true&limit=100")
notes_c = [e for e in (evs_c.get("events") or []) if e.get("mission_id") == job_c["id"]]
log(f"reconnect pull: unread events for job C: {json.dumps(notes_c)[:1000]}")
ev_c["notifications_after_reconnect"] = notes_c
if notes_c:
    s, ack = req("POST", f"/api/monitoring/events/{notes_c[0]['id']}/read")
    log(f"ack first notification: HTTP {s} -> {json.dumps(ack)[:200]}")
    ev_c["ack"] = {"status": s, "body": ack}
EVIDENCE["phases"]["C_scheduled_research"] = ev_c
log("== PHASE C done ==")

# ---------------------------------------------------------------- D: pause/resume/cancel
log("== PHASE D: one-off + pause/resume/cancel cycle ==")
s, b = req("POST", "/api/scheduled", {"instruction": "hi", "schedule": "in 1 minutes"})
assert s == 201, b
job_d = b
log(f"job D created: id={job_d['id']} next_run_at={job_d.get('next_run_at')}")
s, b = req("PATCH", f"/api/scheduled/{job_d['id']}", {"status": "paused"})
assert s == 200, b
log(f"job D paused: status={b.get('status')}")
log("waiting 75s past the due time while paused...")
time.sleep(75)
job_d2 = get_job(job_d["id"])
log(f"job D while paused: status={job_d2['status']} last_run_at={job_d2.get('last_run_at')} last_outcome={job_d2.get('last_outcome')}")
assert job_d2.get("last_run_at") is None, "paused job must not run"
s, b = req("PATCH", f"/api/scheduled/{job_d['id']}", {"status": "active"})
assert s == 200, b
log("job D resumed")
job_d3, dur_d = wait_job_outcome(job_d["id"], timeout=300)
log(f"job D after resume: outcome={job_d3.get('last_outcome')} after {dur_d:.1f}s "
    f"summary={job_d3.get('last_run_summary')}")
s, b = req("POST", "/api/scheduled", {"instruction": "hi", "schedule": "in 1 minutes"})
assert s == 201, b
job_e = b
s, b = req("PATCH", f"/api/scheduled/{job_e['id']}", {"status": "cancelled"})
assert s == 200, b
log(f"job E created then cancelled: id={job_e['id']} status={b.get('status')}")
log("waiting 75s past the due time while cancelled...")
time.sleep(75)
job_e2 = get_job(job_e["id"])
log(f"job E after due: status={job_e2['status']} last_run_at={job_e2.get('last_run_at')} last_outcome={job_e2.get('last_outcome')}")
assert job_e2.get("last_run_at") is None, "cancelled job must not run"
ev_d = {"paused_job": job_d3, "cancelled_job": job_e2}
EVIDENCE["phases"]["D_pause_resume_cancel"] = ev_d
log("== PHASE D done ==")

with open(os.path.join(BDIR, "b-evidence.json"), "w", encoding="utf-8") as f:
    json.dump(EVIDENCE, f, indent=2, default=str)
log("ALL PHASES DONE — evidence in b-evidence.json")
